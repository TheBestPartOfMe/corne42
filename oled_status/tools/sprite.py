#!/usr/bin/env python3
"""Turn a pokemon-colorscripts sprite into a 1-bit LVGL image for the 128x32 OLED.

    python3 sprite.py mimikyu > ../src/mimikyu.c
    python3 sprite.py mimikyu --png preview.png

The colorscript is ANSI text where every cell holds two pixels: '▀' has the top
pixel as foreground and the bottom pixel as background colour, '▄' has only a
bottom pixel, and a space is transparent.
"""

import argparse
import re
import sys

COLORSCRIPTS = "/usr/local/opt/pokemon-colorscripts/colorscripts/small/regular"
MAX_HEIGHT = 32  # OLED height

ANSI = re.compile(r"\x1b\[([0-9;]*)m")


def parse(text):
    """Return rows of RGB tuples (None = transparent), cropped to the sprite."""
    rows = []
    for line in text.rstrip("\n").split("\n"):
        fg = bg = None
        top, bottom = [], []
        pos = 0
        for m in ANSI.finditer(line + "\x1b[m"):
            for ch in line[pos:m.start()]:
                if ch == "▀":
                    top.append(fg)
                    bottom.append(bg)
                elif ch == "▄":
                    top.append(bg)
                    bottom.append(fg)
                else:
                    top.append(bg)
                    bottom.append(bg)
            pos = m.end()
            codes = [int(c) for c in m.group(1).split(";") if c] or [0]
            i = 0
            while i < len(codes):
                if codes[i] == 0:
                    fg = bg = None
                elif codes[i] in (38, 48) and codes[i + 1] == 2:
                    rgb = tuple(codes[i + 2:i + 5])
                    if codes[i] == 38:
                        fg = rgb
                    else:
                        bg = rgb
                    i += 4
                i += 1
        rows += [top, bottom]
    width = max(len(r) for r in rows)
    rows = [r + [None] * (width - len(r)) for r in rows]
    ys = [y for y, r in enumerate(rows) if any(p is not None for p in r)]
    xs = [x for x in range(width) if any(r[x] is not None for r in rows)]
    return [r[xs[0]:xs[-1] + 1] for r in rows[ys[0]:ys[-1] + 1]]


def to_mono(pixels):
    """Reduce to ink/no ink. Returns rows of booleans (True = lit pixel)."""
    out = []
    for y, row in enumerate(pixels):
        line = []
        for x, p in enumerate(row):
            if p is None:
                line.append(False)
                continue
            lum = 0.299 * p[0] + 0.587 * p[1] + 0.114 * p[2]
            if lum < 75:
                line.append(True)  # outline, eyes, ear tips
            elif lum < 140:
                line.append((x + y) % 2 == 0)  # tail: 50 % dither
            else:
                line.append(False)  # body and light shading
        out.append(line)
    return out


def to_c(name, mono):
    h, w = len(mono), len(mono[0])
    stride = (w + 7) // 8
    data = []
    for row in mono:
        for b in range(stride):
            byte = 0
            for bit in range(8):
                x = b * 8 + bit
                # Index 0 is the ink colour, index 1 the background.
                background = x >= w or not row[x]
                byte |= background << (7 - bit)
            data.append(byte)
    lines = [", ".join(f"0x{v:02x}" for v in data[i:i + 12]) for i in range(0, len(data), 12)]
    body = ",\n    ".join(lines)
    return f"""/*
 * Generated by tools/sprite.py from pokemon-colorscripts ({name}). Do not edit.
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
    0x00, 0x00, 0x00, 0xff, /* index 0: ink */
    0xff, 0xff, 0xff, 0xff, /* index 1: background */
    {body},
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {len(data) + 8},
    .data = {name}_map,
}};
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pokemon")
    ap.add_argument("--png", help="write an enlarged preview instead of C code")
    args = ap.parse_args()

    with open(f"{COLORSCRIPTS}/{args.pokemon}", encoding="utf-8") as f:
        mono = to_mono(parse(f.read()))

    h, w = len(mono), len(mono[0])
    if h > MAX_HEIGHT:
        sys.exit(f"{args.pokemon} is {w}x{h} px, the OLED is only {MAX_HEIGHT} px high")
    print(f"{args.pokemon}: {w}x{h} px", file=sys.stderr)

    if args.png:
        from PIL import Image

        img = Image.new("1", (w, h), 0)
        for y, row in enumerate(mono):
            for x, ink in enumerate(row):
                if ink:
                    img.putpixel((x, y), 1)
        img.resize((w * 10, h * 10), Image.NEAREST).save(args.png)
    else:
        sys.stdout.write(to_c(args.pokemon, mono))


if __name__ == "__main__":
    main()
